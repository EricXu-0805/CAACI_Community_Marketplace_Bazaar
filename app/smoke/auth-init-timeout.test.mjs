test('a permanent hang is bounded, has no background retry loop, and permits a single-flight explicit retry', async () => {
  const h = createHarness()
  const transport = observe(h.getSession.promise)
  const started = await start(h)
  await h.clock.advance(10000)
  assertUnavailable(h)
  assert.equal(started.init.settled, true)
  assert.equal(transport.settled, false)
  assert.equal(await h.auth.ensureProfileReady({ force: true }), false)
  await h.clock.advance(60000)
  assertUnavailable(h)
  assert.equal(h.calls.getSession, 1, 'a hung transport does not cause an automatic retry storm')
  assertOwnedDraftProtected(h)
  const retry = h.auth.init()
  assert.notEqual(retry, started.initPromise)
  assert.equal(h.auth.init(), retry)
  await flush()
  assert.equal(h.calls.getSession, 2)
  assert.equal(h.auth.authState.value, 'initializing')
  const retryReady = observe(h.auth.awaitAuthReady())
  await h.clock.advance(10000)
  await retry
  assertUnavailable(h)
  assert.equal(retryReady.value, 'unavailable')
  assert.equal(transport.settled, false)
  assert.equal(h.calls.subscriptions, 1)
  assert.equal(h.calls.unsubscriptions, 0)
  assert.equal(h.calls.transitions.length, 0)
  assert.equal(h.clock.pendingCount(), 0)
  assertOwnedDraftProtected(h)
  h.assertIsolated()
})

