test('an event-owned pending profile outlives the init deadline without premature authenticated readiness or recovery navigation', async () => {
  const slowProfile = deferred()
  const h = createHarness({ getProfile: () => slowProfile.promise })
  const started = await start(h)
  await h.clock.advance(9000)
  h.emit('INITIAL_SESSION', session())
  await h.clock.advance(1000)
  assert.equal(h.scope.getActiveAccountId(), ACCOUNT)
  assert.equal(h.auth.authState.value, 'initializing')
  assert.equal(h.auth.profileLoadState.value, 'loading')
  assert.equal(started.init.settled, true)
  assert.equal(started.ready.settled, false)
  assert.equal(h.auth.requireAuth(), false)
  assert.deepEqual(h.calls.navigation, [])
  const recovery = observe(h.auth.ensureProfileReady({ force: true }))
  assert.equal(recovery.settled, false)
  assert.equal(h.calls.profiles.length, 1)
  await h.clock.advance(2000)
  slowProfile.resolve(profileResponse())
  await flush()
  assertAuthenticated(h)
  assert.equal(await started.readyPromise, 'authenticated')
  assert.equal(recovery.value, true)
  assert.equal(h.auth.requireAuth(), true)
  assert.deepEqual(h.calls.navigation, [])
  assert.deepEqual(h.storage.get(DRAFT), PRIVATE_DRAFT)
  assert.equal(h.clock.pendingCount(), 0)
  h.assertIsolated()
})

test('an already confirmed session keeps profile readiness pending beyond the bounded init deadline', async () => {
  const requests = [deferred(), deferred(), deferred()]
  const h = createHarness({ getProfile: attempt => requests[attempt - 1].promise })
  const started = await start(h)
  h.getSession.resolve({ data: { session: session() }, error: null })
  await flush()
  await h.clock.advance(10000)
  assert.equal(started.init.settled, true)
  assert.equal(started.ready.settled, false)
  assert.equal(h.scope.getActiveAccountId(), ACCOUNT)
  assert.equal(h.auth.authState.value, 'initializing')
  assert.equal(h.auth.profileLoadState.value, 'loading')
  assert.equal(h.auth.requireAuth(), false)
  assert.deepEqual(h.calls.navigation, [])
  assert.deepEqual(h.storage.get(DRAFT), PRIVATE_DRAFT)
  await h.clock.advance(9450)
  assertAuthenticated(h, 'error')
  assert.equal(await started.readyPromise, 'authenticated')
  assert.deepEqual(h.calls.profiles.map(call => call.at), [0, 6350, 13450])
  assert.ok(h.calls.profiles.every(call => call.signal.aborted))
  assert.equal(h.auth.requireAuth(), false)
  assert.deepEqual(h.calls.navigation, [{ method: 'reLaunch', url: '/pages/profile-recovery/index' }])
  assert.deepEqual(h.storage.get(DRAFT), PRIVATE_DRAFT)
  assert.equal(h.calls.captured.filter(call => call.source === 'getSession-init').length, 0)
  h.assertIsolated()
})

for (const failure of ['rpc-error', 'incomplete-profile']) {
  test(`an event-owned ${failure} reaches bounded profile failure and explicit recovery without losing session identity`, async () => {
    const h = createHarness({ getProfile: () => failure === 'rpc-error'
      ? { data: null, error: new Error('synthetic_profile_failure'), status: 503 }
      : { data: { id: ACCOUNT, nickname: 'Missing gate fields' }, error: null, status: 200 } })
    const started = await start(h)
    await h.clock.advance(1000)
    h.emit('INITIAL_SESSION', session())
    await h.clock.advance(1450)
    assert.equal(h.calls.profiles.length, 3)
    assert.deepEqual(h.calls.profiles.map(call => call.at), [1000, 1350, 2450])
    assert.ok(h.calls.profiles.every(call => call.signal.aborted))
    assertAuthenticated(h, 'error')
    assert.equal(await started.readyPromise, 'authenticated')
    assert.equal(h.auth.profileLoadError.value.message,
      failure === 'rpc-error' ? 'synthetic_profile_failure' : 'profile_gate_fields_unavailable')
    assert.equal(h.auth.requireAuth(), false)
    assert.deepEqual(h.calls.navigation, [{ method: 'reLaunch', url: '/pages/profile-recovery/index' }])
    assert.equal(await h.auth.ensureProfileReady(), false, 'profile cooldown prevents an immediate automatic retry')
    assert.deepEqual(h.storage.get(DRAFT), PRIVATE_DRAFT)
    h.setProfileImplementation(() => profileResponse())
    const recovery = h.auth.ensureProfileReady({ force: true })
    await flush()
    assert.equal(await recovery, true)
    assertAuthenticated(h)
    assert.equal(h.auth.profileLoadError.value, null)
    assert.equal(h.auth.requireAuth(), true)
    assert.equal(h.calls.navigation.length, 1)
    assert.equal(h.calls.profiles.length, 4)
    await h.clock.advance(7550)
    assertAuthenticated(h)
    assert.equal(started.init.settled, true)
    h.assertIsolated()
  })
}

test('profile timeouts remain bounded after the session deadline and abandoned replies cannot bypass profile recovery', async () => {
  const abandoned = [deferred(), deferred(), deferred()]
  const h = createHarness({ getProfile: attempt => abandoned[attempt - 1].promise })
  const started = await start(h)
  await h.clock.advance(9000)
  h.emit('INITIAL_SESSION', session())
  await h.clock.advance(1000)
  assert.equal(h.auth.authState.value, 'initializing')
  assert.equal(started.ready.settled, false)
  assert.equal(started.init.settled, true)
  await h.clock.advance(18450)
  assertAuthenticated(h, 'error')
  assert.equal(await started.readyPromise, 'authenticated')
  assert.deepEqual(h.calls.profiles.map(call => call.at), [9000, 15350, 22450])
  assert.ok(h.calls.profiles.every(call => call.signal.aborted))
  for (const request of abandoned) request.resolve(profileResponse())
  await flush()
  assertAuthenticated(h, 'error')
  h.setProfileImplementation(() => profileResponse())
  const recovered = h.auth.ensureProfileReady({ force: true })
  await flush()
  assert.equal(await recovered, true)
  assertAuthenticated(h)
  assert.deepEqual(h.storage.get(DRAFT), PRIVATE_DRAFT)
  h.assertIsolated()
})

