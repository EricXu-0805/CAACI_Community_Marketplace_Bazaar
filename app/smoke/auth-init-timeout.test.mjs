for (const failure of ['rejected-promise', 'resolved-sdk-error']) {
  test(`${failure} is unavailable, preserves owned data, and allows a new attempt after the start-time cooldown`, async () => {
    const h = createHarness()
    const started = await start(h)
    const error = new Error('synthetic_session_failure')
    if (failure === 'rejected-promise') h.getSession.reject(error)
    else h.getSession.resolve({ data: { session: null }, error })
    await flush()
    assertUnavailable(h)
    assert.equal(await started.readyPromise, 'unavailable')
    assert.equal(started.init.settled, true)
    assertOwnedDraftProtected(h)
    assert.equal(h.calls.transitions.length, 0)
    assert.equal(h.auth.init(), started.initPromise)
    await h.clock.advance(2999)
    assert.equal(h.auth.init(), started.initPromise)
    assert.equal(h.calls.getSession, 1)
    await h.clock.advance(1)
    const retry = h.auth.init()
    assert.notEqual(retry, started.initPromise)
    assert.equal(h.auth.init(), retry)
    await flush()
    assert.equal(h.calls.getSession, 2)
    const retryReady = h.auth.awaitAuthReady()
    h.sessionFlights[1].resolve({ data: { session: session() }, error: null })
    await flush()
    await retry
    assert.equal(await retryReady, 'authenticated')
    assertAuthenticated(h)
    assert.equal(h.auth.init(), retry)
    assert.equal(h.calls.subscriptions, 1)
    assert.deepEqual(h.storage.get(DRAFT), PRIVATE_DRAFT)
    h.assertIsolated()
  })
}

