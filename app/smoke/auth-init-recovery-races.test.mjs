test('a direct signIn response after local signOut cannot bypass a blocked persistence boundary', async () => {
  let allowSession = true
  const h = createHarness({ authBoundary: {
    canAcceptSupabaseAuthSession: () => allowSession,
    prepareSupabaseAuthPersistence: async () => { allowSession = true },
  } })
  const loginResponse = deferred()
  h.setSignInImplementation(() => loginResponse.promise)
  h.setSignOutImplementation(async () => {
    // The actual persistence module owns this decision. This test controls
    // only its external answer, exercising useAuth's direct-result guard.
    allowSession = false
    return { accessTokenFound: true, crossRestartProtected: true, storageClearFallbackUsed: false }
  })
  await start(h)
  const login = h.auth.signIn('fixture@example.invalid', 'synthetic-test-password')
  await flush()
  assert.equal(h.calls.directSignIn, 1)
  const logout = h.auth.signOut({ redirect: false })
  assert.equal(allowSession, false)
  assertAnonymous(h)
  await flush()
  assert.equal(await logout, true)
  loginResponse.resolve({ data: { session: session() }, error: null })
  await flush()
  const result = await login
  assert.equal(result.data, null)
  assert.ok(result.error, 'the old direct result must surface rejection to its caller')
  assertAnonymous(h)
  assertOwnedDraftErased(h)
  assert.equal(h.calls.profiles.length, 0)
  assert.equal(h.calls.transitions.length, 1)
  assert.deepEqual(h.calls.navigation, [])
  assert.equal(h.calls.captured.filter(call => call.source === 'auth-signin').length, 1)
  h.getSession.resolve({ data: { session: session() }, error: null })
  await flush()
  assertAnonymous(h)
  h.assertIsolated()
})

test('a delayed local signOut completion cannot erase or navigate over a newer account', async () => {
  const h = createHarness()
  await start(h)
  h.getSession.resolve({ data: { session: session() }, error: null })
  await flush()
  assertAuthenticated(h)
  const revoke = deferred()
  h.setSignOutImplementation(() => revoke.promise)
  const signOut = h.auth.signOut()
  assertAnonymous(h)
  assertOwnedDraftErased(h)
  h.emit('SIGNED_IN', session(OTHER_ACCOUNT))
  await flush()
  assertAuthenticated(h, 'ready', OTHER_ACCOUNT)
  const newDraft = { title: 'New B private draft' }
  assert.equal(h.privacy.writeAccountPrivateStorage(DRAFT, newDraft), true)
  revoke.resolve({ accessTokenFound: true, crossRestartProtected: true, storageClearFallbackUsed: false })
  await flush()
  assert.equal(await signOut, false)
  assertAuthenticated(h, 'ready', OTHER_ACCOUNT)
  assert.deepEqual(h.storage.get(DRAFT), newDraft)
  assert.equal(h.calls.removeAllChannels, 0)
  assert.deepEqual(h.calls.navigation, [])
  h.assertIsolated()
})
