import test from 'node:test'
import assert from 'node:assert/strict'
import {
  ACCOUNT, OTHER_ACCOUNT, OWNER, DRAFT, PRIVATE_DRAFT,
  session, profileResponse, createHarness, deferred, observe, flush, start,
  assertAnonymous, assertAuthenticated, assertUnavailable,
  assertOwnedDraftProtected, assertOwnedDraftErased,
} from './helpers/auth-init-harness.mjs'

function assertProfilePending(harness, userId) {
  assert.equal(harness.scope.getActiveAccountId(), userId)
  assert.equal(harness.auth.authState.value, 'initializing')
  assert.equal(harness.auth.profileLoadState.value, 'loading')
  assert.equal(harness.auth.currentUser.value, null)
  assert.equal(harness.auth.requireAuth(), false)
  assert.deepEqual(harness.calls.navigation, [])
}

for (const signOutAt of [5000, 11000]) {
  test(`local signOut at ${signOutAt} ms invalidates a late session even when the SDK emits no SIGNED_OUT event`, async () => {
    const h = createHarness()
    const started = await start(h)
    await h.clock.advance(signOutAt)
    const signedOut = h.auth.signOut({ redirect: false })
    assertAnonymous(h)
    assertOwnedDraftErased(h)
    await flush()
    assert.equal(await signedOut, true)
    assert.equal(h.calls.localSignOut, 1)
    assert.equal(h.calls.clearBlocked, 1)
    assert.equal(h.calls.removeAllChannels, 1)
    assert.deepEqual(h.calls.navigation, [])
    h.getSession.resolve({ data: { session: session() }, error: null })
    await flush()
    await h.clock.advance(10000)
    assertAnonymous(h)
    assertOwnedDraftErased(h)
    assert.equal(h.calls.profiles.length, 0)
    assert.equal(h.calls.transitions.length, 1, 'only the local authoritative sign-out transition runs')
    assert.equal(started.init.settled, true)
    assert.equal(await h.auth.awaitAuthReady(), 'anonymous')
    h.assertIsolated()
  })
}

