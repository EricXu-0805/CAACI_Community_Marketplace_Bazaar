for (const staleOutcome of ['session', 'anonymous', 'rejection', 'sdk-error']) {
  test(`a newer init attempt rejects the older ${staleOutcome} result while its own session is pending`, async () => {
    const h = createHarness()
    await start(h)
    await h.clock.advance(10000)
    assertUnavailable(h)
    const retry = h.auth.init()
    const ready = observe(h.auth.awaitAuthReady())
    await flush()
    assert.equal(h.calls.getSession, 2)
    await h.clock.advance(500)
    if (staleOutcome === 'session') h.getSession.resolve({ data: { session: session() }, error: null })
    else if (staleOutcome === 'anonymous') h.getSession.resolve({ data: { session: null }, error: null })
    else if (staleOutcome === 'rejection') h.getSession.reject(new Error('stale_attempt_rejection'))
    else h.getSession.resolve({ data: { session: null }, error: new Error('stale_attempt_sdk_error') })
    await flush()
    assert.equal(h.auth.authState.value, 'initializing')
    assert.equal(h.scope.getActiveAccountId(), null)
    assert.equal(ready.settled, false)
    assert.equal(h.calls.profiles.length, 0)
    assert.equal(h.calls.transitions.length, 0)
    assertOwnedDraftProtected(h)
    h.sessionFlights[1].resolve({ data: { session: session(OTHER_ACCOUNT) }, error: null })
    await flush()
    await retry
    assertAuthenticated(h, 'ready', OTHER_ACCOUNT)
    assert.equal(ready.value, 'authenticated')
    assert.equal(h.storage.get(OWNER), OTHER_ACCOUNT)
    assert.equal(h.storage.has(DRAFT), false, 'an authoritative different account clears the prior owner draft')
    const newDraft = { title: 'Account B new draft' }
    assert.equal(h.privacy.writeAccountPrivateStorage(DRAFT, newDraft), true)
    await h.clock.advance(10000)
    assertAuthenticated(h, 'ready', OTHER_ACCOUNT)
    assert.deepEqual(h.storage.get(DRAFT), newDraft)
    assert.equal(h.auth.init(), retry)
    assert.equal(h.calls.getSession, 2)
    assert.equal(h.calls.subscriptions, 1)
    h.assertIsolated()
  })
}

test('an older successful snapshot cannot revive auth after a newer attempt fails; a third eligible attempt can recover', async () => {
  const h = createHarness()
  await start(h)
  await h.clock.advance(10000)
  const second = h.auth.init()
  await flush()
  h.sessionFlights[1].reject(new Error('newest_attempt_failed'))
  await flush()
  await second
  assertUnavailable(h)
  h.getSession.resolve({ data: { session: session() }, error: null })
  await flush()
  assertUnavailable(h)
  assert.equal(h.calls.profiles.length, 0)
  assert.equal(h.calls.transitions.length, 0)
  assertOwnedDraftProtected(h)
  assert.equal(h.auth.init(), second)
  await h.clock.advance(2999)
  assert.equal(h.auth.init(), second)
  await h.clock.advance(1)
  const third = h.auth.init()
  assert.notEqual(third, second)
  await flush()
  assert.equal(h.calls.getSession, 3)
  h.sessionFlights[2].resolve({ data: { session: session() }, error: null })
  await flush()
  await third
  assertAuthenticated(h)
  assert.deepEqual(h.storage.get(DRAFT), PRIVATE_DRAFT)
  assert.equal(h.auth.init(), third)
  assert.equal(h.calls.subscriptions, 1)
  h.assertIsolated()
})

test('an older account event task and session snapshot cannot settle a newer account whose profile is still pending', async () => {
  const profiles = [deferred(), deferred()]
  const h = createHarness({ getProfile: attempt => profiles[attempt - 1].promise })
  const started = await start(h)
  await h.clock.advance(1000)
  h.emit('INITIAL_SESSION', session())
  await flush()
  await h.clock.advance(1000)
  h.emit('SIGNED_IN', session(OTHER_ACCOUNT))
  await flush()
  assert.equal(h.calls.profiles.length, 2)
  assertProfilePending(h, OTHER_ACCOUNT)
  assert.equal(h.storage.has(DRAFT), false)
  const newDraft = { title: 'B owns this after the switch' }
  assert.equal(h.privacy.writeAccountPrivateStorage(DRAFT, newDraft), true)
  h.getSession.resolve({ data: { session: session() }, error: null })
  profiles[0].resolve(profileResponse())
  await flush()
  assertProfilePending(h, OTHER_ACCOUNT)
  assert.equal(started.ready.settled, false)
  assert.deepEqual(h.storage.get(DRAFT), newDraft)
  profiles[1].resolve(profileResponse(OTHER_ACCOUNT))
  await flush()
  assertAuthenticated(h, 'ready', OTHER_ACCOUNT)
  assert.equal(await started.readyPromise, 'authenticated')
  assert.deepEqual(h.storage.get(DRAFT), newDraft)
  h.assertIsolated()
})

test('A to signed-out to A starts a fresh profile request and rejects the earlier A continuation', async () => {
  const profiles = [deferred(), deferred()]
  const h = createHarness({ getProfile: attempt => profiles[attempt - 1].promise })
  const started = await start(h)
  h.emit('INITIAL_SESSION', session())
  await flush()
  h.emit('SIGNED_OUT', null)
  await flush()
  assertAnonymous(h)
  assert.equal(await started.readyPromise, 'anonymous')
  h.emit('SIGNED_IN', session())
  const newReady = observe(h.auth.awaitAuthReady())
  await flush()
  assert.equal(h.calls.profiles.length, 2, 'same id in a new account generation must not share the old profile promise')
  assertProfilePending(h, ACCOUNT)
  const newDraft = { title: 'Fresh A lineage draft' }
  assert.equal(h.privacy.writeAccountPrivateStorage(DRAFT, newDraft), true)
  profiles[0].resolve({ ...profileResponse(), data: { ...profileResponse().data, nickname: 'Obsolete A' } })
  await flush()
  assertProfilePending(h, ACCOUNT)
  assert.equal(newReady.settled, false)
  assert.deepEqual(h.storage.get(DRAFT), newDraft)
  profiles[1].resolve({ ...profileResponse(), data: { ...profileResponse().data, nickname: 'Current A' } })
  await flush()
  assertAuthenticated(h)
  assert.equal(newReady.value, 'authenticated')
  assert.equal(h.auth.currentUser.value.nickname, 'Current A')
  h.getSession.resolve({ data: { session: null }, error: null })
  await flush()
  assertAuthenticated(h)
  assert.deepEqual(h.storage.get(DRAFT), newDraft)
  h.assertIsolated()
})

test('A to B to A rejects both old profile tasks without prematurely settling the newest A generation', async () => {
  const profiles = [deferred(), deferred(), deferred()]
  const h = createHarness({ getProfile: attempt => profiles[attempt - 1].promise })
  const started = await start(h)
  h.emit('INITIAL_SESSION', session())
  await flush()
  h.emit('SIGNED_IN', session(OTHER_ACCOUNT))
  await flush()
  h.emit('SIGNED_IN', session())
  await flush()
  assert.equal(h.calls.profiles.length, 3)
  assert.deepEqual(h.calls.profiles.map(call => call.userId), [ACCOUNT, OTHER_ACCOUNT, ACCOUNT])
  profiles[0].resolve(profileResponse())
  profiles[1].resolve(profileResponse(OTHER_ACCOUNT))
  await flush()
  assertProfilePending(h, ACCOUNT)
  assert.equal(started.ready.settled, false)
  profiles[2].resolve({ ...profileResponse(), data: { ...profileResponse().data, nickname: 'Newest A generation' } })
  await flush()
  assertAuthenticated(h)
  assert.equal(await started.readyPromise, 'authenticated')
  assert.equal(h.auth.currentUser.value.nickname, 'Newest A generation')
  assert.equal(h.calls.transitions.length, 3)
  h.assertIsolated()
})

