#!/bin/sh
set -eu

# Rebuild source inputs. This script never edits the generated distribution.
if [ "$#" -ne 3 ]; then
  echo 'Usage: sh rebuild.sh EMPTY_OUTPUT_DIRECTORY NODE_BINARY NPM_CLI_JS' >&2
  exit 2
fi
SCRIPT_ROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
OUTPUT_DIRECTORY=$1
NODE_BINARY=$2
NPM_CLI=$3
if [ -e "$OUTPUT_DIRECTORY" ]; then
  echo 'The output directory must not exist; existing work is never removed.' >&2
  exit 2
fi
test "$("$NODE_BINARY" --version)" = v22.23.3
test "$("$NODE_BINARY" "$NPM_CLI" --version)" = 11.21.0
mkdir -p "$OUTPUT_DIRECTORY"
OUTPUT_DIRECTORY=$(CDPATH= cd -- "$OUTPUT_DIRECTORY" && pwd)
export PATH="$(dirname -- "$NODE_BINARY"):$PATH"
export SOURCE_DATE_EPOCH=1776519449

python3 - "$SCRIPT_ROOT" <<'PY'
import hashlib, pathlib, sys
root = pathlib.Path(sys.argv[1])
checks = {
 'rollup-v4.60.2-source.tar.gz': '5ae70a325f019a98e59cf73cc26c5d117212fd70921bb14a3e7f3684eca13203',
 'braces-security.patch': '8889beb3edfb82a8a0c9b6354f0b4e6d15212ab79e03cbb399946d116b7f1a3a',
}
for name, expected in checks.items():
    assert hashlib.sha256((root / name).read_bytes()).hexdigest() == expected, name
PY

tar -xzf "$SCRIPT_ROOT/rollup-v4.60.2-source.tar.gz" -C "$OUTPUT_DIRECTORY"
cd "$OUTPUT_DIRECTORY/rollup-4.60.2"
"$NODE_BINARY" "$NPM_CLI" ci --legacy-peer-deps --ignore-scripts --no-audit --no-fund \
  --userconfig=/dev/null --cache "$OUTPUT_DIRECTORY/npm-cache"
"$NODE_BINARY" node_modules/patch-package/index.js
cd node_modules/braces
patch --batch --forward -p1 < "$SCRIPT_ROOT/braces-security.patch"
cd ../..
python3 - "$SCRIPT_ROOT" <<'PY'
import hashlib, json, pathlib, sys
manifest = json.loads((pathlib.Path(sys.argv[1]) / 'braces-source-manifest.json').read_text())
for item in manifest['files']:
    actual = pathlib.Path('node_modules/braces') / item['path']
    assert hashlib.sha256(actual.read_bytes()).hexdigest() == item['sha256'], item['path']
assert hashlib.sha256(pathlib.Path('package-lock.json').read_bytes()).hexdigest() == 'b5a04c560e6ec75a253009f8233d6fcf5b2dac76d452256e1110bab4f136a335'
PY
"$NODE_BINARY" "$NPM_CLI" run build:js:node
python3 - "$SCRIPT_ROOT" <<'PY'
import hashlib, json, pathlib, sys
expected = json.loads((pathlib.Path(sys.argv[1]) / 'build-provenance.json').read_text())['candidate_dist']
actual = {str(path.relative_to('dist')): hashlib.sha256(path.read_bytes()).hexdigest()
          for path in pathlib.Path('dist').rglob('*') if path.is_file()}
assert actual == expected, 'Generated bytes differ from the reviewed build manifest'
print('Verified all 36 generated files against the reviewed build manifest.')
PY
