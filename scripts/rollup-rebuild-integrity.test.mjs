import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import test from 'node:test'

const recipe = await readFile(new URL('../app/build-compat/source-builds/rollup/rebuild.sh', import.meta.url), 'utf8')
const blocks = [...recipe.matchAll(/python3 - "\$SCRIPT_ROOT" <<'PY'\n([\s\S]*?)\nPY/g)].map(match => match[1])
assert.equal(blocks.length, 3, 'extract the three actual recipe validation blocks')

const sha256 = value => createHash('sha256').update(value).digest('hex')
const good = 'harmless matching fixture\n'
const bad = 'harmless mismatching fixture\n'

// Parameterize only fixed expected digest literals to use tiny fixtures. The
// extracted validation logic and real hashlib computations run unchanged.
// No shell recipe, archive extraction, package installation, or build is run.
function fixtureDigests(block, count) {
  const digests = [...block.matchAll(/'[a-f0-9]{64}'/g)]
  assert.equal(digests.length, count)
  return block.replace(/'[a-f0-9]{64}'/g, `'${sha256(good)}'`)
}

const validators = [fixtureDigests(blocks[0], 2), fixtureDigests(blocks[1], 1), blocks[2]]

async function fixture(t) {
  const root = await mkdtemp(path.join(os.tmpdir(), 'caaci-rollup-integrity-'))
  t.after(() => rm(root, { recursive: true, force: true }))
  await mkdir(path.join(root, 'node_modules/braces/lib'), { recursive: true })
  await mkdir(path.join(root, 'dist'))
  await Promise.all([
    ...['rollup-v4.60.2-source.tar.gz', 'braces-security.patch', 'package-lock.json',
      'node_modules/braces/lib/fixture.js', 'dist/fixture.js'].map(name => writeFile(path.join(root, name), good)),
    writeFile(path.join(root, 'braces-source-manifest.json'), JSON.stringify({
      files: [{ path: 'lib/fixture.js', sha256: sha256(good) }],
    })),
    writeFile(path.join(root, 'build-provenance.json'), JSON.stringify({
      candidate_dist: { 'fixture.js': sha256(good) },
    })),
  ])
  return root
}

function validate(block, root, optimize) {
  const result = spawnSync('python3', ['-', root], {
    cwd: root,
    input: block,
    encoding: 'utf8',
    timeout: 10_000,
    env: { PATH: process.env.PATH, PYTHONOPTIMIZE: String(optimize), PYTHONNOUSERSITE: '1' },
  })
  assert.ifError(result.error)
  assert.equal(result.signal, null)
  return result
}

for (const optimize of [0, 1]) {
  for (const [label, index] of [['archive and patch', 0], ['source and lock', 1], ['complete dist', 2]]) {
    test(`Rollup ${label} validator accepts matching fixtures with PYTHONOPTIMIZE=${optimize}`, async t => {
      const root = await fixture(t)
      const result = validate(validators[index], root, optimize)
      assert.equal(result.status, 0, result.stderr)
    })
  }

  for (const [label, index, filename, expectedError] of [
    ['archive digest', 0, 'rollup-v4.60.2-source.tar.gz', 'rollup-v4.60.2-source.tar.gz'],
    ['patch digest', 0, 'braces-security.patch', 'braces-security.patch'],
    ['patched source digest', 1, 'node_modules/braces/lib/fixture.js', 'lib/fixture.js'],
    ['source lock digest', 1, 'package-lock.json', 'package-lock.json'],
    ['dist digest', 2, 'dist/fixture.js', 'Generated bytes differ from the reviewed build manifest'],
    ['extra dist file', 2, 'dist/extra.js', 'Generated bytes differ from the reviewed build manifest'],
  ]) {
    test(`Rollup rejects ${label} mismatch with PYTHONOPTIMIZE=${optimize}`, async t => {
      const root = await fixture(t)
      await writeFile(path.join(root, filename), bad)
      const result = validate(validators[index], root, optimize)
      assert.equal(result.status, 1, `${result.stdout}\n${result.stderr}`)
      assert.equal(result.stderr.trim(), expectedError)
    })
  }

  test(`Rollup rejects missing dist file with PYTHONOPTIMIZE=${optimize}`, async t => {
    const root = await fixture(t)
    await rm(path.join(root, 'dist/fixture.js'))
    const result = validate(validators[2], root, optimize)
    assert.equal(result.status, 1, `${result.stdout}\n${result.stderr}`)
    assert.equal(result.stderr.trim(), 'Generated bytes differ from the reviewed build manifest')
  })
}
